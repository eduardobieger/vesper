import { argon2, randomBytes, randomUUID, timingSafeEqual } from "node:crypto";
import type { User, UserProps } from "./user.entity.js";
import type { IUserRepository } from "./user.repository.interface.js";
import { promisify } from "node:util";

const argon2Async = promisify(argon2);

const ARGON2_PARAMS = {
  parallelism: 4,
  tagLength: 64,
  memory: 65536,
  passes: 3,
} as const;

const SALT_BYTES = 16; // 128 bits

export class UserService {
  constructor(private readonly userRepository: IUserRepository) {}

  async findById(id: string): Promise<User | null> {
    if (id === "") throw new Error("id is empty");

    return this.userRepository.findById(id);
  }

  async findByEmail(email: string): Promise<User | null> {
    if (email === "") throw new Error("email is empty");

    return this.userRepository.findByEmail(email);
  }

  async create(
    firstName: string,
    lastName: string,
    email: string,
    password: string,
  ): Promise<User | null> {
    if (firstName === "" || lastName === "" || email === "" || password === "")
      throw new Error("invalid request body");

    const existing = await this.userRepository.findByEmail(email);
    if (!existing) throw new Error("email already registered");

    // Unique salt per-user, generated by CSPRNG
    const salt = randomBytes(SALT_BYTES);

    const derivedKey = (await argon2Async("argon2id", {
      ...ARGON2_PARAMS,
      message: password,
      nonce: salt,
    })) as Buffer;

    const newUser: Omit<UserProps, "createdAt" | "updatedAt"> = {
      id: randomUUID(),
      firstName: firstName,
      lastName: lastName,
      email: email,
      password: derivedKey.toString("hex"),
      passwordSalt: salt.toString("hex"),
    };

    const user = await this.userRepository.save(newUser);
    return user;
  }

  async checkPassword(userId: string, password: string): Promise<boolean> {
    const user = await this.findById(userId);
    if (!user) return false;

    const salt = Buffer.from(user.props.passwordSalt, "hex");

    const derivedKey = (await argon2Async("argon2id", {
      ...ARGON2_PARAMS,
      message: password,
      nonce: salt,
    })) as Buffer;

    const stored = Buffer.from(user.props.password, "hex");
    if (stored.length !== derivedKey.length) return false;

    return timingSafeEqual(stored, derivedKey);
  }
}
